-- project_3_parking -- PostgreSQL reference schema (course submission).
-- Prefer `flask --app wsgi db upgrade` in environments managed by Alembic.
-- Only run this script on a newly allocated, empty PostgreSQL database/schema.
CREATE TABLE campus_user (
 user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL,
 identity_type VARCHAR(20) NOT NULL,
 department VARCHAR(100) NOT NULL,
 phone VARCHAR(30)
);
CREATE TABLE parking_area (
 area_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 area_name VARCHAR(100) NOT NULL,
 vehicle_type VARCHAR(20) NOT NULL CHECK (vehicle_type IN ('CAR', 'MOTORCYCLE')),
 capacity INTEGER NOT NULL CHECK (capacity > 0),
 hourly_rate NUMERIC(8,2) NOT NULL CHECK (hourly_rate >= 0)
);
CREATE TABLE login_account (
 account_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(50) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('ADMIN','VIEWER')),
 is_active BOOLEAN NOT NULL,
 created_at TIMESTAMPTZ NOT NULL,
 last_login_at TIMESTAMPTZ
);
CREATE TABLE vehicle (
 vehicle_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 plate_no VARCHAR(20) NOT NULL UNIQUE,
 vehicle_type VARCHAR(20) NOT NULL CHECK (vehicle_type IN ('CAR','MOTORCYCLE')),
 user_id INTEGER NOT NULL REFERENCES campus_user(user_id)
);
CREATE TABLE parking_permit (
 permit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 vehicle_id INTEGER NOT NULL REFERENCES vehicle(vehicle_id),
 academic_year VARCHAR(10) NOT NULL,
 issue_date DATE NOT NULL,
 valid_from DATE NOT NULL,
 valid_to DATE NOT NULL,
 permit_fee NUMERIC(10,2) NOT NULL CHECK (permit_fee >= 0),
 payment_method VARCHAR(20),
 paid_at TIMESTAMPTZ,
 CONSTRAINT uq_vehicle_academic_year UNIQUE (vehicle_id, academic_year),
 CONSTRAINT ck_permit_dates CHECK (valid_to >= valid_from),
 CONSTRAINT ck_permit_payment_pair CHECK ((payment_method IS NULL) = (paid_at IS NULL))
);
CREATE TABLE parking_record (
 record_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 plate_no VARCHAR(20) NOT NULL,
 area_id INTEGER NOT NULL REFERENCES parking_area(area_id),
 permit_id INTEGER REFERENCES parking_permit(permit_id),
 entry_time TIMESTAMPTZ NOT NULL,
 exit_time TIMESTAMPTZ,
 parking_fee NUMERIC(10,2) CHECK (parking_fee >= 0),
 payment_method VARCHAR(20),
 paid_at TIMESTAMPTZ,
 CONSTRAINT ck_record_time_order CHECK (exit_time IS NULL OR exit_time > entry_time),
 CONSTRAINT ck_record_payment_pair CHECK ((payment_method IS NULL) = (paid_at IS NULL))
);
CREATE INDEX ix_parking_record_plate_no ON parking_record(plate_no);
CREATE UNIQUE INDEX uq_one_open_record_per_plate ON parking_record(plate_no)
 WHERE exit_time IS NULL;
